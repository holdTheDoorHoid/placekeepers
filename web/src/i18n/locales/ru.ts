const NO_CHANGE = 'без изменений';

/** A change in percent in words: "рост на 61%", "снижение на 3%", "без изменений". */
function changeWords(n: number): string {
  if (n > 0) return `рост на ${formatNumber(n)}%`;
  if (n < 0) return `снижение на ${formatNumber(-n)}%`;
  return 'без изменений';
}

/** " (плюс-минус 6 пунктов)", or nothing when there is no margin: a survey's margin of error. */
function giveOrTake(margin: number | null, unit: 'points' | 'homes'): string {
  if (margin === null) return '';
  return unit === 'points'
    ? ` (плюс-минус ${plural(margin, { one: '# пункт', few: '# пункта', many: '# пунктов', other: '# пункта' })})`
    : ` (плюс-минус ${formatNumber(margin)})`;
}

