// A change in percent in words: "up 61%", "down 3%", "unchanged" (the English helper is private).
function changeWords(n: number): string {
  if (n > 0) return `កើនឡើង ${formatNumber(n)}%`;
  if (n < 0) return `ធ្លាក់ចុះ ${formatNumber(-n)}%`;
  return 'មិន​ប្តូរ';
}

// " (give or take 6 points)", or nothing when there is no margin: a survey's margin of error.
function giveOrTake(margin: number | null, unit: 'points' | 'homes'): string {
  if (margin === null) return '';
  return ` (ឡើងចុះ​ប្រហែល ${unit === 'points' ? plural(margin, { other: '# ពិន្ទុ' }) : formatNumber(margin)})`;
}

